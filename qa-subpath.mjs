import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/usr/local/bin/chromium', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
const errors=[], failed=[];
page.on('pageerror', e=>errors.push(e.message));
page.on('console', m=>{if(m.type()==='error') errors.push(m.text())});
page.on('requestfailed', r=>failed.push(r.url()));
await page.goto('http://127.0.0.1:4176/ds-rpg/', { waitUntil: 'networkidle' });
await page.waitForTimeout(500);
await page.click('[data-nav="classes"]');
await page.waitForTimeout(500);
await page.click('[data-choose="shadowblade"]');
await page.waitForTimeout(1500);
console.log('logo?', await page.locator('.game-logo').count(), 'battle canvas?', await page.locator('#battle-canvas').count());
console.log('errors', errors, 'failed', failed);
await page.screenshot({path:'/tmp/subpath.png'});
await browser.close();
